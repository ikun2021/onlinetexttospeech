type I18nContextType = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: I18nDictionary;
};

const I18nContext = createContext<I18nContextType | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("zh");

  useEffect(() => {
    const saved = localStorage.getItem("preferred_locale") as Locale | null;
    if (saved && translations[saved]) {
      setLocaleState(saved);
    }
  }, []);

  const setLocale = (l: Locale) => {
    if (translations[l]) {
      setLocaleState(l);
      localStorage.setItem("preferred_locale", l);
    }
  };

  const dictionary = translations[locale] || translations.zh;

  return (
    <I18nContext.Provider value={{ locale, setLocale, t: dictionary }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return context;
}
